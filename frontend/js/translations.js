// Language code → SpeechRecognition / SpeechSynthesis locale
const LANG_LOCALE_MAP = {
    en: 'en-US',
    hi: 'hi-IN',
    kn: 'kn-IN',
    mr: 'mr-IN'
};

// Language code → Gemini prompt full name
const LANG_NAME_MAP = {
    en: 'English',
    hi: 'Hindi',
    kn: 'Kannada',
    mr: 'Marwari'
};

/**
 * Change language: save preference + apply translations
 */
function changeLanguage(lang) {
    if (!translations[lang]) lang = 'en';
    localStorage.setItem('language', lang);
    applyTranslations(lang);
    document.documentElement.lang = lang;
    console.log('🌍 Language changed to:', lang);
}

/**
 * Apply translations to all elements with data-i18n / data-i18n-placeholder
 */
function applyTranslations(lang) {
    const t = translations[lang] || translations.en;

    // Text content
    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n');
        if (t[key] !== undefined) {
            el.textContent = t[key];
        }
    });

    // Placeholders
    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
        const key = el.getAttribute('data-i18n-placeholder');
        if (t[key] !== undefined) {
            el.placeholder = t[key];
        }
    });

    // Update speech recognition language
    if (typeof recognition !== 'undefined' && recognition) {
        recognition.lang = LANG_LOCALE_MAP[lang] || 'en-US';
    }

    // Stop any ongoing speech synthesis
    if (window.speechSynthesis) {
        window.speechSynthesis.cancel();
    }
}

/**
 * Init language on page load
 */
function initLanguage() {
    const savedLang = localStorage.getItem('language') || 'en';
    const select = document.getElementById('languageSelect');
    if (select) select.value = savedLang;
    applyTranslations(savedLang);
}

// Auto-init on DOM ready
document.addEventListener('DOMContentLoaded', initLanguage);

// Make global for inline handlers
window.changeLanguage = changeLanguage;
